/*# 図書館 貸出システム（Java コンソールアプリ）

オブジェクト指向（参照の共有・has-a の関係・責務の分け方）の練習として作った、図書館の貸出システムです。

## 課題の内容

- 会員が本を借りられる
- 返却期限を過ぎると会員が「延滞中」になり、延滞中は新しく借りられない
- 延滞の状態は**継承を使わず**、フィールドで表す
- メニュー用のクラスを別に作り、図書館のインスタンスは**1つだけ作って渡す**

## クラス構成

| クラス | 役割 |
|---|---|
| `Main` | `Library` を1つだけ作り、`Menu` に渡して起動する |
| `Library` | 本（`Book`）と会員（`Member`）のリストを持つ |
| `Book` | 本の名前・番号・貸出中かどうかを持つ |
| `Member` | 会員。借りているか、延滞しているか、日数のカウントを持つ |
| `Menu` | メニュー画面。入店・貸出・日数の進行などを呼び出す |
| `Borrow` | 「借りる」の画面と処理 |
| `EndDay` | 「一日が終了する」の処理。借りている会員の日数を進める |
| `MainMenu` | メニュー系クラスの共通インターフェース |

## 動かし方

Java 15 以上が必要です（テキストブロックを使っています）。

```
cd src
javac -d ../out Main.java Book/*.java Library/*.java Menu/*.java
java -cp ../out Main
```

Eclipse などの IDE では、`Main` を実行してください。

## 現在の実装状況

実装済み

- 入店（会員の登録）と、退館して次の客を迎える
- 本を借りる（貸出中の本は借りられない）
- 一日が終了する（本を借りている会員だけ、客ごとに日数を数える）

未実装

- 返却
- 検索
- 3日を超えたら延滞にする判定、延滞中は借りられない制限
- システムの終了

## 設計で意識したこと

- 延滞は継承ではなく、`Member` のフィールドで表す
- `Library` は `Main` で1回だけ `new` して、`Menu` から `Borrow` へ渡して共有する
- 日数は会員ごとに数える。`new` を実行した回数だけオブジェクトが作られるので、会員ごとに別々の `EndDay` を渡す*/
